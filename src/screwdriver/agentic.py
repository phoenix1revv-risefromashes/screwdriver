def _safe_recommended_commands(commands: list[str]) -> list[str]:
    return [command for command in commands if _validated_read_only_command(command)]


def _validated_read_only_command(command: str) -> bool:
    """Allow only executable, shell-free commands from a narrow read-only catalog."""

    if any(token in command for token in ("|", ";", "&&", "||", ">", "<", "`", "$(")):
        return False
    try:
        parts = shlex.split(command)
    except ValueError:
        return False
    if not parts:
        return False
    joined = " ".join(parts)
    fixed = {
        "ros2 node list",
        "ros2 topic list -t",
        "printenv ROS_DISTRO",
        "ps -eo pid,comm,%cpu,%mem --sort=-%cpu",
        "ps -eo pid,comm,%cpu,%mem --sort=-%mem",
        "df -hT",
        "sensors",
        "free -h",
        "uptime",
        "lsblk --json",
    }
    if joined in fixed:
        return True
    patterns = (
        r"ros2 node info /[A-Za-z0-9_~/.-]{1,160}",
        r"ros2 topic info /[A-Za-z0-9_~/.-]{1,160} --verbose",
        r"ros2 param list /[A-Za-z0-9_~/.-]{1,160}",
        r"udevadm info --query=property --name /dev/[A-Za-z0-9_./-]{1,160}",
        r"lsof -- /dev/[A-Za-z0-9_./-]{1,160}",
        r"systemctl --no-pager --full status [A-Za-z0-9@_.-]{1,120}",
        r"journalctl --no-pager -k --since -10min -n 150",
        r"ip -details link show [A-Za-z0-9_.:-]{1,40}",
    )
    return any(re.fullmatch(pattern, joined) for pattern in patterns)


def _deduplicate_text(values: list[str]) -> list[str]:
    output: list[str] = []
    seen: set[str] = set()
    for value in values:
        key = value.casefold()
        if key not in seen:
            seen.add(key)
            output.append(value)
    return output


def _deduplicate_issues(issues: list[DiagnosticIssue]) -> list[DiagnosticIssue]:
    result: list[DiagnosticIssue] = []
    seen: set[str] = set()
    for issue in issues:
        key = _semantic_issue_key(issue)
        if key not in seen:
            seen.add(key)
            result.append(issue)
    return result


def _semantic_issue_key(issue: DiagnosticIssue) -> str:
    text = f"{issue.code} {issue.title}".casefold()
    if (
        "ros" in text
        and "environment" in text
        and any(token in text for token in ("source", "shell", "recover"))
    ):
        return "ros-environment-context"
    if "serial" in text and any(token in text for token in ("access", "permission")):
        device = re.search(r"/dev/[a-z0-9._/-]+", text)
        return "serial-access:" + (device.group(0) if device else issue.code.casefold())
    normalized_title = re.sub(r"[^a-z0-9]+", " ", issue.title.casefold()).strip()
    return normalized_title or issue.code.casefold()
