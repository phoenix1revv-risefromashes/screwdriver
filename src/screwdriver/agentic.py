def _records(value: Any) -> list[dict[str, Any]]:
    if not isinstance(value, list):
        return []
    return [cast(dict[str, Any], item) for item in value if isinstance(item, dict)]


def _mapping(value: Any) -> dict[str, Any]:
    return cast(dict[str, Any], value) if isinstance(value, dict) else {}


def _clean_text(value: Any) -> str | None:
    if value is None:
        return None
    text = str(value).strip()
    return text or None


def _string_list(value: Any) -> list[str]:
    if not isinstance(value, list):
        return []
    return [text for item in value if (text := _clean_text(item))]


def _display(value: Any) -> str:
    if value is None or value == "":
        return "Unknown"
    if isinstance(value, (list, dict)):
        return json.dumps(value, ensure_ascii=False)
    return str(value)


def _h(value: Any) -> str:
    return html.escape(str(value), quote=True)


def _bytes(value: Any) -> str:
    if not isinstance(value, (int, float)):
        return "Unknown"
    amount = float(value)
    for unit in ("B", "KiB", "MiB", "GiB", "TiB"):
        if amount < 1024 or unit == "TiB":
            return f"{amount:.1f} {unit}"
        amount /= 1024
    return "Unknown"


def _percent(value: Any) -> str:
    return f"{float(value):.1f}%" if isinstance(value, (int, float)) else "Unknown"


def _severity_label(value: str) -> str:
    return {"error": "HIGH", "warning": "MEDIUM", "info": "INFO"}.get(value, "LOW")


def _valid_severity(value: Any, existing: DiagnosticIssue | None) -> str:
    text = str(value or "").upper()
    return (
        text
        if text in {"CRITICAL", "HIGH", "MEDIUM", "LOW", "INFO"}
        else (existing.severity if existing else "LOW")
    )


def _valid_evidence_level(value: Any, existing: DiagnosticIssue | None) -> str:
    text = str(value or "").upper()
    return (
        text
        if text in {"VERIFIED", "CORRELATED", "INFERRED", "UNKNOWN"}
        else (existing.evidence_level if existing else "INFERRED")
    )


def _bounded_int(value: Any, default: int) -> int:
    try:
        return max(0, min(100, int(value)))
    except (TypeError, ValueError):
        return default


def _recommendation_steps(recommendation: str | None, code: str) -> list[str]:
    if recommendation:
        parts = [part.strip(" .") for part in re.split(r"(?:\n|;|(?<=\.)\s+)", recommendation)]
        steps = [part + "." for part in parts if part]
        if steps:
            return steps
    return [
        "Confirm the observation using the listed read-only diagnostic commands.",
        f"Inspect the configuration or component associated with {code}.",
        "Apply one human-approved correction.",
        "Repeat the check and confirm the success criteria.",
    ]


def _default_cause(code: str) -> str:
    categories = {
        "ROS_": "ROS environment, discovery, endpoint, or configuration inconsistency.",
        "SERIAL_": "Serial identity, driver binding, permissions, or port ownership inconsistency.",
        "CPU_": "Sustained workload, runaway process, or insufficient compute headroom.",
        "MEMORY_": "Application growth, memory leak, cache pressure, or insufficient RAM.",
        "FILESYSTEM_": "Logs, datasets, containers, or application files consumed available storage.",
        "THERMAL_": "Cooling, airflow, workload, fan control, or thermal-interface problem.",
    }
    return next(
        (text for prefix, text in categories.items() if code.startswith(prefix)),
        "A component or configuration does not match the expected operating state.",
    )


def _commands_for_code(code: str, finding: dict[str, Any]) -> list[str]:
    evidence = str(finding.get("evidence") or "")
    if code.startswith("ROS_"):
        return ["ros2 node list", "ros2 topic list -t"]
    if code.startswith("SERIAL_"):
        match = re.search(
            r"/dev/[A-Za-z0-9_./-]+", evidence + " " + str(finding.get("summary") or "")
        )
        port = match.group(0) if match else "/dev/ttyUSB0"
        return [f"udevadm info --query=property --name {port}", f"lsof -- {port}"]
    if code.startswith(("CPU_", "MEMORY_")):
        return ["ps -eo pid,comm,%cpu,%mem --sort=-%cpu | head -20"]
    if code.startswith("FILESYSTEM_"):
        return ["df -hT", "du -xhd1 /var 2>/dev/null | sort -h"]
    if code.startswith("THERMAL_"):
        return ["sensors", "cat /sys/class/thermal/thermal_zone*/temp"]
    return []


def _success_for_code(code: str) -> str:
    if code.startswith("ROS_"):
        return (
            "The expected ROS nodes and endpoints are visible with consistent environment settings."
        )
    if code.startswith("SERIAL_"):
        return "The intended process can identify and access the stable serial device without contention."
    if code.startswith("CPU_"):
        return "CPU usage remains below the warning threshold under the expected workload."
    if code.startswith("MEMORY_"):
        return "Memory usage remains below the warning threshold without growth over time."
    if code.startswith("FILESYSTEM_"):
        return "The affected filesystem has sufficient free capacity for logs and runtime data."
    if code.startswith("THERMAL_"):
        return "Temperature remains below the platform limit during the expected workload."
    return "A repeat inspection no longer reports this finding."


def _safe_recommended_commands(commands: list[str]) -> list[str]:
    blocked = re.compile(
        r"\b(sudo|rm|mv|cp|chmod|chown|apt|dnf|yum|pacman|pip install|systemctl restart|"
        r"systemctl stop|kill|pkill|reboot|shutdown|ros2 topic pub|ros2 service call)\b",
        re.IGNORECASE,
    )
    return [command for command in commands if not blocked.search(command)]


def _deduplicate_text(values: list[str]) -> list[str]:
    output: list[str] = []
    seen: set[str] = set()
    for value in values:
        key = value.casefold()
        if key not in seen:
            seen.add(key)
            output.append(value)
    return output


def _deduplicate_issues(issues: list[DiagnosticIssue]) -> list[DiagnosticIssue]:
    result: list[DiagnosticIssue] = []
    seen: set[str] = set()
    for issue in issues:
        if issue.code not in seen:
            seen.add(issue.code)
            result.append(issue)
    return result
