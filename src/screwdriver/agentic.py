def _approach_adds_value(instruction: str, commands: list[str]) -> bool:
    text = instruction.casefold().strip(" .")
    if not text:
        return False
    if any(command.startswith("ps ") for command in commands) and (
        "identify" in text and "process" in text
    ):
        return False
    if "verify" in text and any(
        token in text for token in ("usage", "again", "repeat", "re-run", "rerun")
    ):
        return False
    if "run ros2 node list" in text and "ros2 node list" in commands:
        return False
    return True


def _instruction_sentence(value: str) -> str:
    text = value.strip()
    if not text:
        return text
    text = text[0].upper() + text[1:]
    return text if text.endswith((".", "!", "?")) else text + "."


