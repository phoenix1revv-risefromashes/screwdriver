def _looks_like_configuration_finding(code: str) -> bool:
    normalized = code.upper()
    return normalized.startswith(("ROS_", "DDS_", "SERIAL_", "CAN_", "NETWORK_")) or any(
        token in normalized for token in _CONFIGURATION_CODE_TOKENS
    )


def _classification_for_finding(
    code: str,
    severity: str,
    snapshot: dict[str, Any],
) -> str:
    """Classify deterministic findings without hiding real warnings.

    The deterministic collector is authoritative on whether an observed condition is
    a warning/error. Only explicitly context-only or optional findings are downgraded
    to NEEDS_CONFIRMATION. Unknown warning codes remain visible instead of silently
    becoming INFO.
    """

    if code == "ROS_ENVIRONMENT_NOT_SOURCED":
        return "CONFIGURATION_WARNING"
    if code in _CONTEXT_ONLY_FINDING_CODES:
        return "NEEDS_CONFIRMATION"
    if (
        code.startswith("SERIAL_")
        and any(
            token in code for token in ("NOTE", "INCOMPLETE", "UNVERIFIED", "UNKNOWN", "OPTIONAL")
        )
        and not _serial_finding_is_operationally_relevant(code, snapshot)
    ):
        return "NEEDS_CONFIRMATION"
    if severity == "error":
        return "CONFIRMED_FAILURE"
    if severity == "warning":
        if code.startswith(_DEGRADED_CODE_PREFIXES):
            return "DEGRADED"
        if _looks_like_configuration_finding(code):
            return "CONFIGURATION_WARNING"
        # A deterministic WARNING is itself evidence of a real observed problem.
        # Keep it visible even when the code is new to the agentic layer.
        return "DEGRADED"
    return "ADVISORY"


def _serial_finding_is_operationally_relevant(code: str, snapshot: dict[str, Any]) -> bool:
    if not code.startswith("SERIAL_"):
        return False
    ros_text = json.dumps(snapshot.get("ros_device_inventory", []), ensure_ascii=False)
    for device in _records(snapshot.get("serial_devices")):
        for identity in (device.get("port"), device.get("stable_id_path")):
            if identity and str(identity) in ros_text:
                return True
    return False


def _expected_state_for_code(code: str) -> str:
    if code == "ROS_ENVIRONMENT_NOT_SOURCED":
        return "The Screwdriver inspection shell has the installed ROS 2 distribution sourced so the ros2 CLI can inspect the live graph."
    if code.startswith(("ROS_", "DDS_")):
        return (
            "The configured ROS/DDS environment and expected runtime graph are mutually consistent."
        )
    if code.startswith("SERIAL_"):
        return "Only serial interfaces required by the robot profile or runtime need stable, read-write access."
    if code.startswith(("CAN_", "NETWORK_")):
        return "The required communication interface is configured and in the expected operational state."
    if "SERVICE" in code or code.startswith(("PROCESS_", "CONTAINER_", "DOCKER_")):
        return "The required runtime service/process/container is present and in its expected active state."
    if any(token in code for token in ("DRIVER", "DEVICE", "CAMERA", "AUDIO", "DISPLAY")):
        return "The detected hardware has the expected driver/interface state and is available to its intended runtime consumer."
    if code.startswith("CPU_"):
        return "CPU usage remains below the warning threshold during the expected workload."
    if code.startswith("MEMORY_"):
        return "Memory use remains below the warning threshold without sustained growth."
    if code.startswith(("FILESYSTEM_", "STORAGE_", "DISK_")):
        return "Runtime storage retains enough healthy capacity for logs, data, and application writes."
    if code.startswith(("THERMAL_", "POWER_", "GPU_")):
        return "The compute platform remains within its expected thermal, power, and accelerator operating limits."
    return "The observed subsystem matches the expected configured and operational state."


def _impact_for_code(code: str, classification: str) -> str:
    if code == "ROS_ENVIRONMENT_NOT_SOURCED":
        return (
            "Screwdriver cannot reliably inspect the live ROS 2 graph from the current shell until the installed "
            "ROS environment is sourced. This limits diagnostic visibility; it does not prove the deployed robot "
            "ROS runtime is down."
        )
    if classification == "NEEDS_CONFIRMATION":
        return "No operational impact is proven until the operator confirms this component is required."
    if code.startswith(("ROS_", "DDS_")):
        return "ROS discovery, startup consistency, endpoint communication, or graph visibility may be affected."
    if code.startswith("SERIAL_"):
        return "A process that requires this serial interface may be unable to identify, open, or communicate with it reliably."
    if code.startswith(("CAN_", "NETWORK_")):
        return "Robot communication, telemetry, control, or external connectivity may be unavailable or degraded."
    if "SERVICE" in code or code.startswith(("PROCESS_", "CONTAINER_", "DOCKER_")):
        return "The software capability owned by this runtime component may be unavailable or degraded."
    if any(token in code for token in ("DRIVER", "DEVICE", "CAMERA", "AUDIO", "DISPLAY")):
        return "The affected hardware may be detected by Linux but unavailable to the runtime or end-to-end robot capability."
    if code.startswith("CPU_"):
        return "Control, perception, or interaction workloads may miss timing targets."
    if code.startswith("MEMORY_"):
        return "Processes may experience reclaim pressure, latency, or termination if usage grows."
    if code.startswith(("FILESYSTEM_", "STORAGE_", "DISK_")):
        return "Logs, recordings, datasets, containers, or application writes may fail or become unreliable."
    if code.startswith(("THERMAL_", "POWER_", "GPU_")):
        return "Compute performance or availability may degrade through throttling, accelerator loss, or protective shutdown."
    return "The deterministic inspection observed a degraded or misconfigured subsystem; the exact downstream capability impact may still require correlation."


