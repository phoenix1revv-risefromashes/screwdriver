def _commands_for_code(code: str, finding: dict[str, Any], snapshot: dict[str, Any]) -> list[str]:
    """Return only exact diagnostic commands whose targets come from evidence."""

    evidence = " ".join(
        str(finding.get(key) or "") for key in ("evidence", "summary", "recommendation")
    )
    if code == "ROS_ENVIRONMENT_NOT_SOURCED":
        return ["printenv ROS_DISTRO", "ros2 node list", "ros2 topic list -t"]
    if code.startswith("ROS_"):
        return ["ros2 node list", "ros2 topic list -t"]
    if code.startswith("SERIAL_"):
        known_ports = {
            str(device.get("port"))
            for device in _records(snapshot.get("serial_devices"))
            if device.get("port")
        }
        match = re.search(r"/dev/[A-Za-z0-9_./-]+", evidence)
        if match is None or match.group(0) not in known_ports:
            return []
        port = match.group(0)
        return [f"udevadm info --query=property --name {port}", f"lsof -- {port}"]
    if code.startswith("CPU_"):
        return ["uptime", "ps -eo pid,comm,%cpu,%mem --sort=-%cpu"]
    if code.startswith("MEMORY_"):
        return ["free -h", "ps -eo pid,comm,%cpu,%mem --sort=-%mem"]
    if code.startswith(("FILESYSTEM_", "STORAGE_", "DISK_")):
        return ["df -hT", "lsblk --json"]
    if code.startswith("THERMAL_"):
        return ["sensors"]
    if code.startswith(("CAN_", "NETWORK_")):
        interface = _finding_interface(snapshot, evidence, require_can=code.startswith("CAN_"))
        if interface:
            commands = [f"ip -details link show {interface}"]
            if code.startswith("CAN_"):
                commands.append(f"timeout 5 candump {interface}")
            return commands
    if "SERVICE" in code or code.startswith(("PROCESS_", "CONTAINER_", "DOCKER_")):
        unit = re.search(r"\b[A-Za-z0-9@_.-]+\.(?:service|socket|timer)\b", evidence)
        if unit:
            return [f"systemctl --no-pager --full status {unit.group(0)}"]
    device_match = re.search(r"/dev/[A-Za-z0-9_./-]+", evidence)
    if device_match and device_match.group(0) in json.dumps(snapshot, ensure_ascii=False):
        device_path = device_match.group(0)
        return [
            f"udevadm info --query=property --name {device_path}",
            f"lsof -- {device_path}",
        ]
    if "DRIVER" in code:
        return ["journalctl --no-pager -k --since -10min -n 150"]
    return []


def _finding_interface(snapshot: dict[str, Any], evidence: str, *, require_can: bool) -> str | None:
    candidates: list[tuple[str, bool]] = []
    for item in _records(_mapping(snapshot.get("network")).get("interfaces")):
        name = str(item.get("name") or "").strip()
        if name:
            text = " ".join(str(value or "") for value in item.values()).casefold()
            candidates.append((name, "can" in text or name.casefold().startswith("can")))
    for item in _records(snapshot.get("hardware_bus_inventory")):
        details = _mapping(item.get("details"))
        name = str(
            details.get("interface") or details.get("channel") or item.get("name") or ""
        ).strip()
        if not name or name.startswith("/dev/"):
            continue
        text = " ".join(
            str(value or "")
            for value in (item.get("name"), details.get("kind"), details.get("bus"), name)
        ).casefold()
        candidates.append((name, "can" in text or name.casefold().startswith("can")))

    evidence_cf = evidence.casefold()
    for name, is_can in candidates:
        if require_can and not is_can:
            continue
        if re.search(
            rf"(?<![A-Za-z0-9_.:-]){re.escape(name.casefold())}(?![A-Za-z0-9_.:-])", evidence_cf
        ):
            return name
    matching = [name for name, is_can in candidates if is_can or not require_can]
    if len(set(matching)) == 1:
        return matching[0]
    return None


