def _valid_diagnosis_status(value: Any, existing: DiagnosticIssue | None) -> str:
    text = str(value or "").upper()
    allowed = {"CONFIRMED", "PROBABLE", "PARTIAL", "UNRESOLVED"}
    if text in allowed:
        return text
    if existing is not None:
        return existing.diagnosis_status
    return "UNRESOLVED"


def _bounded_int(value: Any, default: int) -> int:
    try:
        return max(0, min(100, int(value)))
    except (TypeError, ValueError):
        return default


