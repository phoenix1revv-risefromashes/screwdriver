def _bounded_value(
    value: Any,
    depth: int = 0,
    *,
    path: str = "$",
    omissions: list[str] | None = None,
) -> Any:
    omissions = omissions if omissions is not None else []
    if depth > 7:
        omissions.append(f"{path}: depth limit")
        return "[truncated]"
    if isinstance(value, str):
        redacted = _redact_cloud_text(value)
        if len(redacted) > 1200:
            omissions.append(f"{path}: string truncated from {len(redacted)} characters")
        return redacted[:1200]
    if isinstance(value, list):
        normalized: list[Any] = []
        seen: set[str] = set()
        duplicate_count = 0
        for item in value:
            if isinstance(item, (dict, list)):
                marker = json.dumps(item, sort_keys=True, default=str, ensure_ascii=False)
                if marker in seen:
                    duplicate_count += 1
                    continue
                seen.add(marker)
            normalized.append(item)
        if duplicate_count:
            omissions.append(f"{path}: {duplicate_count} duplicate records removed")
        if len(normalized) > 100:
            omissions.append(f"{path}: {len(normalized) - 100} records omitted")
        return [
            _bounded_value(item, depth + 1, path=f"{path}[{index}]", omissions=omissions)
            for index, item in enumerate(normalized[:100])
        ]
    if isinstance(value, dict):
        redacted_keys = {
            "machine_id",
            "serial_number",
            "mac_address",
            "default_gateway",
            "stable_id_path",
            "physical_path",
        }
        return {
            str(key): (
                "[redacted]"
                if str(key) in redacted_keys
                else _bounded_value(
                    item,
                    depth + 1,
                    path=f"{path}.{key}",
                    omissions=omissions,
                )
            )
            for key, item in value.items()
        }
    return value


def _redact_cloud_text(value: str) -> str:
    text = re.sub(r"(?i)/dev/serial/by-id/[^\s,;]+", "/dev/serial/by-id/[redacted]", value)
    text = re.sub(r"(?i)\b(?:[0-9a-f]{2}:){5}[0-9a-f]{2}\b", "[redacted-mac]", text)
    text = re.sub(r"\b[0-9A-Fa-f]{24,}\b", "[redacted-identifier]", text)
    return text


def _parse_probe_requests(value: Any) -> list[ProbeRequest]:
    requests: list[ProbeRequest] = []
    for item in _records(value):
        probe = _clean_text(item.get("probe"))
        target = _clean_text(item.get("target"))
        reason = _clean_text(item.get("reason")) or "Additional evidence requested."
        if probe:
            requests.append(ProbeRequest(probe=probe, target=target, reason=reason))
    return requests[:_MAX_PROBES]


def _run_probe_requests(
    snapshot: dict[str, Any],
    requests: list[ProbeRequest],
) -> list[ProbeResult]:
    hostname = str(_mapping(snapshot.get("identity")).get("hostname") or "")
    if hostname and hostname not in {socket.gethostname(), socket.getfqdn()}:
        return []
    results: list[ProbeResult] = []
    for request in requests[:_MAX_PROBES]:
        command = _probe_command(request)
        if command is None:
            results.append(
                ProbeResult(
                    request.probe,
                    request.target,
                    (),
                    "rejected",
                    stderr="Probe name or target is outside the validated read-only catalog.",
                )
            )
            continue
        executable = shutil.which(command[0])
        if executable is None:
            results.append(
                ProbeResult(
                    request.probe,
                    request.target,
                    command,
                    "unavailable",
                    stderr=f"Required executable not found: {command[0]}",
                )
            )
            continue
        command = (executable, *command[1:])
        started = time.monotonic()
        try:
            completed = subprocess.run(
                command,
                check=False,
                capture_output=True,
                text=True,
                timeout=5,
                env=_probe_environment(snapshot),
            )
        except (OSError, subprocess.TimeoutExpired) as exception:
            results.append(
                ProbeResult(
                    request.probe,
                    request.target,
                    command,
                    "failed",
                    stderr=str(exception),
                    duration_ms=int((time.monotonic() - started) * 1000),
                )
            )
            continue
        stdout = completed.stdout.strip()
        stderr = completed.stderr.strip()
        truncated = len(stdout) > _MAX_PROBE_OUTPUT or len(stderr) > _MAX_PROBE_OUTPUT
        results.append(
            ProbeResult(
                request.probe,
                request.target,
                command,
                "completed" if completed.returncode == 0 else "nonzero",
                stdout=stdout[:_MAX_PROBE_OUTPUT],
                stderr=stderr[:_MAX_PROBE_OUTPUT],
                return_code=completed.returncode,
                duration_ms=int((time.monotonic() - started) * 1000),
                truncated=truncated,
            )
        )
    return results


def _probe_environment(snapshot: dict[str, Any]) -> dict[str, str]:
    """Reuse recovered ROS identity fields when the snapshot recorded them."""

    environment = os.environ.copy()
    ros = _ros_overview(snapshot)
    for key, snapshot_key in (
        ("ROS_DISTRO", "ros_distro"),
        ("ROS_DOMAIN_ID", "domain_id"),
        ("RMW_IMPLEMENTATION", "middleware"),
    ):
        value = ros.get(snapshot_key)
        if value not in (None, "", "default"):
            environment[key] = str(value)
    return environment


def _probe_command(request: ProbeRequest) -> tuple[str, ...] | None:
    target = request.target
    ros_name = re.compile(r"^/[A-Za-z0-9_~/.-]{1,160}$")
    device = re.compile(r"^/dev/[A-Za-z0-9_./-]{1,160}$")
    unit = re.compile(r"^[A-Za-z0-9@_.-]{1,120}$")
    interface = re.compile(r"^[A-Za-z0-9_.:-]{1,40}$")
    if request.probe == "ros_node_info" and target and ros_name.fullmatch(target):
        return ("ros2", "node", "info", target)
    if request.probe == "ros_topic_info" and target and ros_name.fullmatch(target):
        return ("ros2", "topic", "info", target, "--verbose")
    if request.probe == "ros_param_list" and target and ros_name.fullmatch(target):
        return ("ros2", "param", "list", target)
    if request.probe in {"device_metadata", "port_owner"} and target:
        if ".." in target or not device.fullmatch(target):
            return None
        return (
            ("udevadm", "info", "--query=property", "--name", target)
            if request.probe == "device_metadata"
            else ("lsof", "--", target)
        )
    if request.probe == "service_status" and target and unit.fullmatch(target):
        return ("systemctl", "--no-pager", "--full", "status", target)
    if request.probe == "recent_kernel_logs" and target is None:
        return ("journalctl", "--no-pager", "-k", "--since", "-10min", "-n", "150")
    if request.probe == "network_link" and target and interface.fullmatch(target):
        return ("ip", "-details", "link", "show", target)
    return None


def _merge_agent_issues(
    snapshot: dict[str, Any],
    deterministic: list[DiagnosticIssue],
    value: Any,
) -> list[DiagnosticIssue]:
    by_code = {issue.code: issue for issue in deterministic}
    for record in _records(value):
        code = (_clean_text(record.get("code")) or "AGENT_INFERENCE").upper()
        existing = by_code.get(code)
        references = _string_list(record.get("evidence_references"))
        valid_references = [
            reference for reference in references if _evidence_reference_exists(snapshot, reference)
        ]
        # New model hypotheses must point to real snapshot evidence. A polished
        # paragraph without a resolvable source is not accepted as a finding.
        if existing is None and not valid_references:
            continue
        issue = DiagnosticIssue(
            code=code,
            title=_clean_text(record.get("title")) or (existing.title if existing else code),
            severity=_valid_severity(record.get("severity"), existing),
            confidence=_bounded_int(
                record.get("confidence"),
                existing.confidence if existing else 60,
            ),
            classification=_valid_classification(record.get("classification"), existing),
            observation_confidence=_bounded_int(
                record.get("observation_confidence"),
                existing.observation_confidence if existing else 60,
            ),
            diagnosis_confidence=_bounded_int(
                record.get("diagnosis_confidence"),
                existing.diagnosis_confidence if existing else 45,
            ),
            expected_state=_clean_text(record.get("expected_state"))
            or (existing.expected_state if existing else "No expected state was supplied."),
            operational_impact=_clean_text(record.get("operational_impact"))
            or (existing.operational_impact if existing else "Impact has not been established."),
            evidence_references=valid_references
            or (existing.evidence_references if existing else []),
            evidence_level=_valid_evidence_level(record.get("evidence_level"), existing),
            observed=_string_list(record.get("observed"))
            or (existing.observed if existing else []),
            probable_causes=_string_list(record.get("probable_causes"))
            or (existing.probable_causes if existing else []),
            primary_approach=_string_list(record.get("primary_approach"))
            or (existing.primary_approach if existing else []),
            alternative_approaches=[
                _string_list(item) for item in record.get("alternative_approaches", [])
            ]
            if isinstance(record.get("alternative_approaches"), list)
            else (existing.alternative_approaches if existing else []),
            diagnostic_commands=_safe_recommended_commands(
                _string_list(record.get("diagnostic_commands"))
            )
            or (existing.diagnostic_commands if existing else []),
            success_criteria=_string_list(record.get("success_criteria"))
            or (existing.success_criteria if existing else []),
        )
        if existing is None and not issue.observed:
            continue
        by_code[code] = issue
    return _deduplicate_issues(list(by_code.values()))


def _evidence_reference_exists(snapshot: dict[str, Any], reference: str) -> bool:
    """Resolve a bounded dotted/list reference against the snapshot."""

    if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*(?:\[\d+\]|\.[A-Za-z_][A-Za-z0-9_]*)*", reference):
        return False
    root_match = re.match(r"[A-Za-z_][A-Za-z0-9_]*", reference)
    if root_match is None:
        return False
    current: Any = snapshot
    position = 0
    token_pattern = re.compile(r"(?:^|\.)([A-Za-z_][A-Za-z0-9_]*)|\[(\d+)\]")
    for match in token_pattern.finditer(reference):
        if match.start() != position:
            return False
        position = match.end()
        key, index = match.groups()
        if key is not None:
            if not isinstance(current, dict) or key not in current:
                return False
            current = current[key]
        else:
            if not isinstance(current, list):
                return False
            item_index = int(index)
            if item_index >= len(current):
                return False
            current = current[item_index]
    return position == len(reference)


