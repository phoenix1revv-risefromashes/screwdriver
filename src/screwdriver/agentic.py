_ANTHROPIC_ENDPOINT = "https://api.anthropic.com/v1/messages"
_ANTHROPIC_VERSION = "2023-06-01"
_DEFAULT_MODEL = "claude-sonnet-5"
_DEFAULT_EFFORT = "medium"
_MAX_OUTPUT_TOKENS = 12_000
_MAX_PROBES = 4
_MAX_PROBE_OUTPUT = 12_000


@dataclass(frozen=True, slots=True)
class AgentReportPaths:
    """Paths generated by one agentic analysis."""

    blueprint: Path
    diagnostics: Path
    analysis: Path


@dataclass(slots=True)
class DiagnosticIssue:
    """One evidence-grounded problem and its repair guidance."""

    code: str
    title: str
    severity: str
    confidence: int
    observed: list[str] = field(default_factory=list)
    probable_causes: list[str] = field(default_factory=list)
    primary_approach: list[str] = field(default_factory=list)
    alternative_approaches: list[list[str]] = field(default_factory=list)
    diagnostic_commands: list[str] = field(default_factory=list)
    success_criteria: list[str] = field(default_factory=list)
    evidence_level: str = "VERIFIED"

    def to_dict(self) -> dict[str, object]:
        return {
            "code": self.code,
            "title": self.title,
            "severity": self.severity,
            "confidence": self.confidence,
            "evidence_level": self.evidence_level,
            "observed": self.observed,
            "probable_causes": self.probable_causes,
            "primary_approach": self.primary_approach,
            "alternative_approaches": self.alternative_approaches,
            "diagnostic_commands": self.diagnostic_commands,
            "success_criteria": self.success_criteria,
        }


@dataclass(frozen=True, slots=True)
class ProbeRequest:
    """A model-requested probe selected from a closed read-only catalog."""

    probe: str
    target: str | None
    reason: str


@dataclass(frozen=True, slots=True)
class ProbeResult:
    """Bounded output from one approved read-only probe."""

    probe: str
    target: str | None
    command: tuple[str, ...]
    state: str
    output: str

    def to_dict(self) -> dict[str, object]:
        return {
            "probe": self.probe,
            "target": self.target,
            "command": list(self.command),
            "state": self.state,
            "output": self.output,
        }


@dataclass(slots=True)
class AnalysisOutcome:
    """Structured result returned by the agentic orchestration layer."""

    paths: AgentReportPaths
    provider_status: str
    summary: str
    architecture_observations: list[str]
    unknowns: list[str]
    issues: list[DiagnosticIssue]
    probes: list[ProbeResult]


def analyze_snapshot_file(
    snapshot_path: Path,
    output_directory: Path,
    *,
    provider: str = "anthropic",
    model: str = _DEFAULT_MODEL,
    effort: str = _DEFAULT_EFFORT,
    investigate: bool = False,
    focus: str | None = None,
) -> AnalysisOutcome:
    """Analyze a saved snapshot and write the two user-facing HTML reports."""

    snapshot = _load_snapshot(snapshot_path)
    paths = AgentReportPaths(
        blueprint=output_directory / "system-blueprint.html",
        diagnostics=output_directory / "diagnostic-report.html",
        analysis=output_directory / "agent-analysis.json",
    )
    deterministic_issues = _deterministic_issues(snapshot)
    summary = _deterministic_summary(snapshot)
    observations = _architecture_observations(snapshot)
    unknowns = _unknowns(snapshot)
    probes: list[ProbeResult] = []
    provider_status = "deterministic analysis"

    if provider not in {"anthropic", "none"}:
        raise ValueError("provider must be one of: anthropic, none")
    if effort not in {"low", "medium", "high", "xhigh"}:
        raise ValueError("effort must be one of: low, medium, high, xhigh")

    if provider != "none":
        try:
            response = _anthropic_analysis(
                snapshot,
                deterministic_issues,
                model=model,
                effort=effort,
                focus=focus,
            )
        except AgentProviderError as exception:
            provider_status = f"Claude unavailable; deterministic fallback ({exception})"
        else:
            provider_status = f"Anthropic Claude model {model} (effort {effort})"
            summary = _clean_text(response.get("summary")) or summary
            observations = _string_list(response.get("architecture_observations")) or observations
            unknowns = _string_list(response.get("unknowns")) or unknowns
            deterministic_issues = _merge_agent_issues(
                deterministic_issues,
                response.get("issues"),
            )
            requests = _parse_probe_requests(response.get("probe_requests"))

            if investigate and requests:
                probes = _run_probe_requests(snapshot, requests)
                if probes:
                    try:
                        revised = _anthropic_analysis(
                            snapshot,
                            deterministic_issues,
                            model=model,
                            effort=effort,
                            focus=focus,
                            probe_results=probes,
                        )
                    except AgentProviderError:
                        provider_status += "; probe re-analysis unavailable"
                    else:
                        provider_status += f"; {len(probes)} read-only probes evaluated"
                        summary = _clean_text(revised.get("summary")) or summary
                        observations = (
                            _string_list(revised.get("architecture_observations")) or observations
                        )
                        unknowns = _string_list(revised.get("unknowns")) or unknowns
                        deterministic_issues = _merge_agent_issues(
                            deterministic_issues,
                            revised.get("issues"),
                        )

    output_directory.mkdir(parents=True, exist_ok=True)
    paths.blueprint.write_text(
        _build_blueprint_html(
            snapshot,
            summary=summary,
            observations=observations,
            unknowns=unknowns,
            provider_status=provider_status,
            focus=focus,
        ),
        encoding="utf-8",
    )
    paths.diagnostics.write_text(
        _build_diagnostic_html(
            snapshot,
            issues=deterministic_issues,
            probes=probes,
            provider_status=provider_status,
        ),
        encoding="utf-8",
    )
    paths.analysis.write_text(
        json.dumps(
            {
                "source_snapshot": str(snapshot_path),
                "provider_status": provider_status,
                "focus": focus,
                "summary": summary,
                "architecture_observations": observations,
                "unknowns": unknowns,
                "issues": [issue.to_dict() for issue in deterministic_issues],
                "read_only_probes": [probe.to_dict() for probe in probes],
                "repairs_executed": False,
            },
            indent=2,
        )
        + "\n",
        encoding="utf-8",
    )
    return AnalysisOutcome(
        paths=paths,
        provider_status=provider_status,
        summary=summary,
        architecture_observations=observations,
        unknowns=unknowns,
        issues=deterministic_issues,
        probes=probes,
    )


class AgentProviderError(RuntimeError):
    """Raised when the configured model provider cannot return valid analysis."""


def _load_snapshot(path: Path) -> dict[str, Any]:
    try:
        raw = json.loads(path.read_text(encoding="utf-8"))
    except OSError as exception:
        raise ValueError(f"cannot read snapshot: {exception}") from exception
    except json.JSONDecodeError as exception:
        raise ValueError(f"snapshot is not valid JSON: {exception}") from exception

    if not isinstance(raw, dict):
        raise ValueError("snapshot root must be a JSON object")
    required = {"identity", "operating_system", "cpu", "memory", "network", "findings"}
    missing = sorted(required - raw.keys())
    if missing:
        raise ValueError("snapshot is missing required fields: " + ", ".join(missing))
    return cast(dict[str, Any], raw)


def _deterministic_summary(snapshot: dict[str, Any]) -> str:
    identity = _mapping(snapshot.get("identity"))
    os_info = _mapping(snapshot.get("operating_system"))
    platform = _mapping(snapshot.get("platform"))
    ros = _ros_overview(snapshot)
    devices = _current_ros_device_names(snapshot)
    machine = platform.get("product_name") or platform.get("board_name") or "Linux computer"
    graph = ""
    if ros:
        graph = (
            f" The live ROS 2 graph contains {ros.get('nodes', 0)} nodes and "
            f"{ros.get('topics', 0)} topics."
        )
    device_text = f" ROS currently uses {', '.join(devices)}." if devices else ""
    return (
        f"{identity.get('hostname', 'This robotic computer')} is a {machine} running "
        f"{os_info.get('distribution', 'Linux')}.{graph}{device_text}"
    )


def _architecture_observations(snapshot: dict[str, Any]) -> list[str]:
    observations: list[str] = []
    ros = _ros_overview(snapshot)
    if ros:
        observations.append(
            "ROS 2 uses "
            f"{ros.get('middleware') or 'an unspecified DDS implementation'} on domain "
            f"{ros.get('domain_id') if ros.get('domain_id') is not None else 'unknown'}."
        )
    for device in _records(snapshot.get("ros_device_inventory"))[:12]:
        details = _mapping(device.get("details"))
        kind = details.get("kind") or device.get("name")
        node = details.get("ros_node") or details.get("hardware_node")
        channel = details.get("topics") or details.get("channel")
        physical = details.get("physical_component")
        chain = " → ".join(str(value) for value in (physical, node, channel) if value)
        if chain:
            observations.append(f"{kind}: {chain}")
    return observations


def _unknowns(snapshot: dict[str, Any]) -> list[str]:
    unknowns: list[str] = []
    for device in _records(snapshot.get("ros_device_inventory")):
        details = _mapping(device.get("details"))
        if not details.get("physical_component"):
            unknowns.append(
                f"{details.get('kind') or device.get('name')}: physical hardware is not proven."
            )
    for device in _records(snapshot.get("serial_devices")):
        if not device.get("stable_id_path"):
            unknowns.append(
                f"{device.get('port', 'Serial device')}: no stable by-id identity was found."
            )
    return _deduplicate_text(unknowns)


def _deterministic_issues(snapshot: dict[str, Any]) -> list[DiagnosticIssue]:
    issues: list[DiagnosticIssue] = []
    for finding in _records(snapshot.get("findings")):
        severity = str(finding.get("severity") or "info").lower()
        code = str(finding.get("code") or "UNCLASSIFIED_FINDING")
        if severity == "info" and code.endswith(("_HEALTHY", "_DETECTED", "_DISCOVERED")):
            continue
        summary = _clean_text(finding.get("summary")) or code.replace("_", " ").title()
        evidence = _clean_text(finding.get("evidence"))
        recommendation = _clean_text(finding.get("recommendation"))
        steps = _recommendation_steps(recommendation, code)
        issues.append(
            DiagnosticIssue(
                code=code,
                title=summary.removeprefix("[OK] "),
                severity=_severity_label(severity),
                confidence=100 if evidence else 85,
                observed=[evidence] if evidence else [summary],
                probable_causes=[_default_cause(code)],
                primary_approach=steps,
                diagnostic_commands=_commands_for_code(code, finding),
                success_criteria=[_success_for_code(code)],
                evidence_level="VERIFIED" if evidence else "CORRELATED",
            )
        )

    runtime = _ros_overview(snapshot)
    if runtime and str(runtime.get("state") or "").upper() in {"UNAVAILABLE", "FAILED"}:
        if not any(issue.code == "ROS_RUNTIME_UNAVAILABLE" for issue in issues):
            issues.append(
                DiagnosticIssue(
                    code="ROS_RUNTIME_UNAVAILABLE",
                    title="ROS 2 runtime graph could not be inspected",
                    severity="HIGH",
                    confidence=95,
                    observed=[f"ROS graph state: {runtime.get('state')}"],
                    probable_causes=[
                        "The scanner and ROS processes may use different environment or DDS settings."
                    ],
                    primary_approach=[
                        "Source the same ROS underlay and workspace used to launch the robot.",
                        "Verify ROS_DOMAIN_ID and RMW_IMPLEMENTATION.",
                        "Run ros2 node list and confirm that the graph is visible.",
                        "Repeat the Screwdriver inspection.",
                    ],
                    diagnostic_commands=["ros2 node list", "ros2 topic list -t"],
                    success_criteria=[
                        "The ROS graph is discovered and reports active nodes/topics."
                    ],
                )
            )
    return _deduplicate_issues(issues)


def _anthropic_analysis(
    snapshot: dict[str, Any],
    issues: list[DiagnosticIssue],
    *,
    model: str,
    effort: str,
    focus: str | None,
    probe_results: list[ProbeResult] | None = None,
) -> dict[str, Any]:
    api_key = os.environ.get("ANTHROPIC_API_KEY", "").strip()
    if not api_key:
        raise AgentProviderError("ANTHROPIC_API_KEY is not set")

    schema = _agent_schema()
    evidence = {
        "snapshot": _evidence_view(snapshot),
        "deterministic_issues": [issue.to_dict() for issue in issues],
        "focus": focus,
        "read_only_probe_results": [probe.to_dict() for probe in probe_results or []],
    }
    system = (
        "You are Screwdriver's robotics diagnostic engineer. Use only supplied evidence. "
        "Never claim hardware was tested, never invent facts, and distinguish verified, "
        "correlated, inferred, and unknown information. Preserve every deterministic issue. "
        "For each problem, provide ordered troubleshooting approaches and measurable success "
        "criteria. You may request only the listed read-only probes. Never recommend that the "
        "software execute repairs, actuator commands, permission changes, installs, restarts, "
        "or configuration edits automatically. Return JSON matching the supplied schema."
    )
    if probe_results:
        system += " Probe results are final evidence; do not request additional probes."
    user = (
        "Build (1) a concise system-blueprint narrative and (2) an evidence-grounded "
        "diagnostic plan. Allowed probes: ros_node_info, ros_topic_info, ros_param_list, "
        "device_metadata, port_owner, service_status, recent_kernel_logs, network_link.\n\n"
        + json.dumps(evidence, separators=(",", ":"))
    )
    payload = {
        "model": model,
        "max_tokens": _MAX_OUTPUT_TOKENS,
        "system": system,
        "messages": [
            {"role": "user", "content": user},
        ],
        "output_config": {
            "effort": effort,
            "format": {
                "type": "json_schema",
                "schema": schema,
            },
        },
    }
    request = urllib.request.Request(
        _ANTHROPIC_ENDPOINT,
        data=json.dumps(payload).encode("utf-8"),
        headers={
            "Content-Type": "application/json",
            "X-Api-Key": api_key,
            "Anthropic-Version": _ANTHROPIC_VERSION,
        },
        method="POST",
    )
    try:
        with urllib.request.urlopen(request, timeout=120) as response:  # noqa: S310
            body = json.loads(response.read().decode("utf-8"))
    except urllib.error.HTTPError as exception:
        raise AgentProviderError(_anthropic_http_error(exception)) from exception
    except (OSError, TimeoutError, urllib.error.URLError, json.JSONDecodeError) as exception:
        raise AgentProviderError(str(exception)) from exception

    response_body = _mapping(body)
    stop_reason = response_body.get("stop_reason")
    if stop_reason == "refusal":
        raise AgentProviderError("Claude refused the diagnostic request")
    if stop_reason == "max_tokens":
        raise AgentProviderError("Claude response reached the configured output limit")

    content = "".join(
        str(block.get("text") or "")
        for block in _records(response_body.get("content"))
        if block.get("type") == "text"
    )
    if not content:
        raise AgentProviderError("Claude returned no text content")
    try:
        result = json.loads(content)
    except json.JSONDecodeError as exception:
        raise AgentProviderError("Claude returned invalid structured JSON") from exception
    if not isinstance(result, dict):
        raise AgentProviderError("Claude result must be a JSON object")
    missing = {
        "summary",
        "architecture_observations",
        "unknowns",
        "issues",
        "probe_requests",
    } - result.keys()
    if missing:
        raise AgentProviderError(
            "Claude result is missing required fields: " + ", ".join(sorted(missing))
        )
    return cast(dict[str, Any], result)


def _anthropic_http_error(exception: urllib.error.HTTPError) -> str:
    """Return a bounded API error without exposing credentials or request content."""

    message = "request failed"
    try:
        body = json.loads(exception.read().decode("utf-8"))
    except (OSError, UnicodeDecodeError, json.JSONDecodeError):
        pass
    else:
        error = _mapping(_mapping(body).get("error"))
        message = str(error.get("message") or message).strip()[:300]
    return f"Anthropic API HTTP {exception.code}: {message}"


