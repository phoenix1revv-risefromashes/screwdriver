def _filtered_ros_devices(devices: list[dict[str, Any]], terms: tuple[str, ...]) -> str:
    selected = [item for item in devices if any(term in json.dumps(item).lower() for term in terms)]
    return (
        _ros_device_table(selected)
        if selected
        else '<p class="muted">No matching active architecture was identified.</p>'
    )


def _component_table(records: list[dict[str, Any]], keys: tuple[str, ...]) -> str:
    if not records:
        return '<p class="muted">No items detected.</p>'
    return _table(
        [key.replace("_", " ").title() for key in keys],
        [[record.get(key) for key in keys] for record in records],
    )


def _named_list(records: list[dict[str, Any]]) -> str:
    return _unordered_list([str(item.get("name") or "Unnamed") for item in records])


def _table(headers: list[str], rows: list[list[Any]]) -> str:
    if not rows:
        return '<p class="muted">No records available.</p>'
    head = "".join(f"<th>{_h(value)}</th>" for value in headers)
    body = "".join(
        "<tr>" + "".join(f"<td>{_h(_display(value))}</td>" for value in row) + "</tr>"
        for row in rows
    )
    return f"<table><thead><tr>{head}</tr></thead><tbody>{body}</tbody></table>"


def _key_value_table(values: dict[str, Any]) -> str:
    return _table(["Property", "Value"], [[key, value] for key, value in values.items()])


def _ordered_list(values: list[str], *, empty: str = "No items available.") -> str:
    return (
        f"<ol>{''.join(f'<li>{_h(value)}</li>' for value in values)}</ol>"
        if values
        else f'<p class="muted">{_h(empty)}</p>'
    )


def _unordered_list(values: list[str], *, empty: str = "No items available.") -> str:
    return (
        f"<ul>{''.join(f'<li>{_h(value)}</li>' for value in values)}</ul>"
        if values
        else f'<p class="muted">{_h(empty)}</p>'
    )


def _metric(label: str, value: Any) -> str:
    return (
        f'<div class="metric"><span>{_h(label)}</span><strong>{_h(_display(value))}</strong></div>'
    )


def _badge(value: str) -> str:
    return f"<span>{_h(value)}</span>"


def _details(label: str, value: Any) -> str:
    return f"<details><summary>{_h(label)}</summary><pre>{_h(json.dumps(value, indent=2))}</pre></details>"


def _records(value: Any) -> list[dict[str, Any]]:
    if not isinstance(value, list):
        return []
    return [cast(dict[str, Any], item) for item in value if isinstance(item, dict)]


def _mapping(value: Any) -> dict[str, Any]:
    return cast(dict[str, Any], value) if isinstance(value, dict) else {}


def _clean_text(value: Any) -> str | None:
    if value is None:
        return None
    text = str(value).strip()
    return text or None


def _string_list(value: Any) -> list[str]:
    if not isinstance(value, list):
        return []
    return [text for item in value if (text := _clean_text(item))]


def _display(value: Any) -> str:
    if value is None or value == "":
        return "Unknown"
    if isinstance(value, (list, dict)):
        return json.dumps(value, ensure_ascii=False)
    return str(value)


def _h(value: Any) -> str:
    return html.escape(str(value), quote=True)


def _bytes(value: Any) -> str:
    if not isinstance(value, (int, float)):
        return "Unknown"
    amount = float(value)
    for unit in ("B", "KiB", "MiB", "GiB", "TiB"):
        if amount < 1024 or unit == "TiB":
            return f"{amount:.1f} {unit}"
        amount /= 1024
    return "Unknown"


def _percent(value: Any) -> str:
    return f"{float(value):.1f}%" if isinstance(value, (int, float)) else "Unknown"


def _severity_label(value: str) -> str:
    return {"error": "HIGH", "warning": "MEDIUM", "info": "INFO"}.get(value, "LOW")


def _valid_severity(value: Any, existing: DiagnosticIssue | None) -> str:
    text = str(value or "").upper()
    return (
        text
        if text in {"CRITICAL", "HIGH", "MEDIUM", "LOW", "INFO"}
        else (existing.severity if existing else "LOW")
    )


def _valid_evidence_level(value: Any, existing: DiagnosticIssue | None) -> str:
    text = str(value or "").upper()
    return (
        text
        if text in {"VERIFIED", "CORRELATED", "INFERRED", "UNKNOWN"}
        else (existing.evidence_level if existing else "INFERRED")
    )


def _valid_classification(value: Any, existing: DiagnosticIssue | None) -> str:
    text = str(value or "").upper()
    allowed = {
        "CONFIRMED_FAILURE",
        "DEGRADED",
        "CONFIGURATION_WARNING",
        "ADVISORY",
        "NEEDS_CONFIRMATION",
    }
    return text if text in allowed else (existing.classification if existing else "NEEDS_CONFIRMATION")


def _bounded_int(value: Any, default: int) -> int:
    try:
        return max(0, min(100, int(value)))
    except (TypeError, ValueError):
        return default


def _recommendation_steps(recommendation: str | None, code: str) -> list[str]:
    if recommendation:
        parts = [part.strip(" .") for part in re.split(r"(?:\n|;|(?<=\.)\s+)", recommendation)]
