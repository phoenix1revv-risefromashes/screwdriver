def _provider_schema(report_mode: str) -> dict[str, Any]:
    """Extend the compact agent schema only at the provider boundary.

    The report engine intentionally requests only intelligence that is rendered.
    Current provider adapters still expect the legacy summary/observation/unknown
    fields, so keep those compatibility fields out of ``_agent_schema`` and add
    them only to the schema sent across the provider boundary.
    """

    schema = _agent_schema(report_mode)
    properties = dict(schema["properties"])
    properties.update(
        {
            "summary": {"type": "string"},
            "architecture_observations": {"type": "array", "items": {"type": "string"}},
            "unknowns": {"type": "array", "items": {"type": "string"}},
        }
    )
