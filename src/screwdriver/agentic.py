def _deterministic_recommended_steps(
    code: str,
    primary_approach: list[str],
    commands: list[str],
    snapshot: dict[str, Any],
) -> list[dict[str, str]]:
    """Build short, useful troubleshooting paths instead of generic report filler."""

    if code == "ROS_ENVIRONMENT_NOT_SOURCED":
        ros = _ros_overview(snapshot)
        distro = str(ros.get("ros_distro") or ros.get("distro") or "").strip()
        if not distro:
            for item in _records(snapshot.get("software_stack_inventory")):
                details = _mapping(item.get("details"))
                name = str(item.get("name") or "").casefold()
                if "ros" in name and details.get("version"):
                    distro = str(details.get("version"))
                    break
        setup_path = f"/opt/ros/{distro}/setup.bash" if distro else ""
        ros_steps = [
            _step(
                "Check whether this shell has ROS 2 loaded.",
                command="printenv ROS_DISTRO",
                look_for=distro or "The installed ROS 2 distribution name.",
                meaning="Empty output confirms the current shell is not sourced.",
                next_step="If empty, confirm the installed ROS setup file and source it in this same shell.",
            )
        ]
        if setup_path:
            ros_steps.extend(
                [
                    _step(
                        "Confirm the installed ROS 2 setup file.",
                        command=f"ls -l {setup_path}",
                        look_for=f"An existing readable {setup_path} file.",
                        meaning="This proves the exact setup file before changing the shell environment.",
                        next_step="If the file exists, source it; if it does not, inspect the installed ROS distribution instead of guessing another path.",
                    ),
                    _step(
                        "Load the installed ROS 2 environment into the current shell.",
                        command=f"source {setup_path}",
                        look_for="No error from the source command.",
                        meaning="The current shell now has the ROS environment needed by the ros2 CLI.",
                        next_step="Verify ROS_DISTRO and then inspect the graph.",
                    ),
                ]
            )
        ros_steps.extend(
            [
                _step(
                    "Verify that the ROS 2 CLI is now using the expected environment.",
                    command="printenv ROS_DISTRO",
                    look_for=distro or "A non-empty ROS distribution value.",
                    meaning="A populated ROS_DISTRO confirms the shell environment is loaded.",
                    next_step="If correct, inspect the live ROS graph; if empty, do not treat graph failures as a robot-runtime failure yet.",
                ),
                _step(
                    "Inspect the live ROS 2 graph from the corrected shell.",
                    command="ros2 node list",
                    look_for="The robot's active ROS 2 nodes, or an empty list if no graph is running.",
                    meaning="Visible nodes prove the earlier inspection gap was caused by the unsourced shell. An empty list means the shell is fixed but no active graph is currently visible.",
                    next_step="If Screwdriver is launched from another shell/service, make that launch environment source the same ROS setup before inspection.",
                ),
            ]
        )
        return ros_steps[:6]

    if code == "SERIAL_PERMISSION_DENIED":
        port = _serial_port_from_commands(commands)
        device = _serial_device_for_port(snapshot, port)
        node = _mapping(device.get("device_node"))
        group = str(node.get("group") or "").strip()
        if port:
            serial_steps = [
                _step(
                    f"Confirm the current permissions on {port}.",
                    command=f"stat -c '%A %U %G %n' {port}",
                    look_for=(
                        f"The device group is {group} and the mode grants that group read/write access."
                        if group
                        else "The device owner, group, and read/write mode."
                    ),
                    meaning="This identifies the exact Linux permission boundary causing the access failure.",
                    next_step="Check whether the current runtime user belongs to the device group.",
                ),
                _step(
                    "Check the current user's supplementary groups.",
                    command="id -nG",
                    look_for=(
                        group if group else "The device-owning group shown by the previous command."
                    ),
                    meaning=(
                        f"If {group} is missing, the current user cannot inherit the device's group permissions."
                        if group
                        else "The user must belong to the group that owns the device when group read/write bits are required."
                    ),
                    next_step=(
                        f"If {group} is missing, add the current user to that group; if it is already present, inspect udev/ACL rules instead."
                        if group
                        else "If the required group is missing, add the current user to it; otherwise inspect udev/ACL rules."
                    ),
                ),
            ]
            if group:
                serial_steps.extend(
                    [
                        _step(
                            f"Add the current user to {group} only if the previous check proved membership is missing.",
                            command=f"sudo usermod -aG {group} $USER",
                            look_for="The command completes without an error.",
                            meaning=f"This grants the current user membership in the evidence-backed device group {group}.",
                            next_step="Start a new login session (or otherwise refresh group membership) before testing the device again.",
                        ),
                        _step(
                            "Verify the refreshed session has the required group.",
                            command="id -nG",
                            look_for=group,
                            meaning="The new session now carries the group permission required by the device node.",
                            next_step=f"Test read/write access to {port}; if access still fails, inspect udev/ACL rules rather than repeating the group change.",
                        ),
                    ]
                )
            serial_steps.append(
                _step(
                    f"Verify that the current user can now open {port} for read/write access.",
                    command=f"test -r {port} -a -w {port} && echo read-write",
                    look_for="read-write",
                    meaning="This directly proves the original Linux access failure is resolved for the current user.",
                    next_step="If access is restored, continue with the robot process that owns this serial interface; if not, inspect udev/ACL rules and device ownership.",
                )
            )
            return serial_steps[:6]

    steps: list[dict[str, str]] = []
    for command in commands[:4]:
        if command.startswith("screwdriver inspect"):
            continue
        steps.append(
            _step(
                _command_instruction(code, command),
                command=command,
                look_for=_command_look_for(code, command),
                meaning=_command_meaning(code, command),
                next_step=_command_next_step(code, command),
            )
        )

    for instruction in primary_approach:
        if len(steps) >= 6 or not _approach_adds_value(instruction, commands):
            continue
        steps.append(
            _step(
                _instruction_sentence(instruction),
                look_for=_manual_step_look_for(code),
                meaning="Use this result to identify the exact component or setting responsible for the problem.",
                next_step="Apply the smallest correction supported by the evidence, then verify the original condition directly.",
            )
        )
    return steps[:6]


def _serial_port_from_commands(commands: list[str]) -> str:
    for command in commands:
        match = re.search(r"/dev/[A-Za-z0-9_./-]+", command)
        if match:
            return match.group(0)
    return ""


def _serial_device_for_port(snapshot: dict[str, Any], port: str) -> dict[str, Any]:
    if not port:
        return {}
    for device in _records(snapshot.get("serial_devices")):
        node = _mapping(device.get("device_node"))
        if port in {str(device.get("port") or ""), str(node.get("path") or "")}:
            return device
    return {}


