class ProgressCallback(Protocol):
    def __call__(self, number: int, label: str, waiting: bool = False) -> None: ...


@dataclass(frozen=True, slots=True)
class AgentReportPaths:
    """Paths generated by one agentic analysis."""

    compact: Path
    blueprint: Path
    diagnostics: Path
    analysis: Path


@dataclass(slots=True)
class DiagnosticIssue:
    """One evidence-grounded problem and its repair guidance."""

    code: str
    title: str
    severity: str
    confidence: int
    classification: str = "NEEDS_CONFIRMATION"
    observation_confidence: int = 0
    diagnosis_confidence: int = 0
    expected_state: str = "No expected state was supplied."
    operational_impact: str = "Impact has not been established."
    evidence_references: list[str] = field(default_factory=list)
    observed: list[str] = field(default_factory=list)
    probable_causes: list[str] = field(default_factory=list)
    primary_approach: list[str] = field(default_factory=list)
    alternative_approaches: list[list[str]] = field(default_factory=list)
    diagnostic_commands: list[str] = field(default_factory=list)
    success_criteria: list[str] = field(default_factory=list)
    evidence_level: str = "VERIFIED"

    def to_dict(self) -> dict[str, object]:
        return {
            "code": self.code,
            "title": self.title,
            "severity": self.severity,
            "confidence": self.confidence,
            "classification": self.classification,
            "observation_confidence": self.observation_confidence or self.confidence,
            "diagnosis_confidence": self.diagnosis_confidence or self.confidence,
            "expected_state": self.expected_state,
            "operational_impact": self.operational_impact,
            "evidence_references": self.evidence_references,
            "evidence_level": self.evidence_level,
            "observed": self.observed,
            "probable_causes": self.probable_causes,
            "primary_approach": self.primary_approach,
            "alternative_approaches": self.alternative_approaches,
            "diagnostic_commands": self.diagnostic_commands,
            "success_criteria": self.success_criteria,
        }


@dataclass(frozen=True, slots=True)
class ProbeRequest:
    """A model-requested probe selected from a closed read-only catalog."""

    probe: str
    target: str | None
    reason: str


@dataclass(frozen=True, slots=True)
class ProbeResult:
    """Bounded output from one approved read-only probe."""

    probe: str
    target: str | None
    command: tuple[str, ...]
    state: str
    stdout: str = ""
    stderr: str = ""
    return_code: int | None = None
    duration_ms: int = 0
    truncated: bool = False

    @property
    def output(self) -> str:
        """Backward-compatible combined probe text for older callers."""

        return "\n".join(value for value in (self.stdout, self.stderr) if value)

    def to_dict(self) -> dict[str, object]:
        return {
            "probe": self.probe,
            "target": self.target,
            "command": list(self.command),
            "state": self.state,
            "stdout": self.stdout,
            "stderr": self.stderr,
            "return_code": self.return_code,
            "duration_ms": self.duration_ms,
            "truncated": self.truncated,
        }


@dataclass(slots=True)
class AnalysisOutcome:
    """Structured result returned by the agentic orchestration layer."""

    paths: AgentReportPaths
    provider_status: str
    summary: str
    architecture_observations: list[str]
    unknowns: list[str]
    issues: list[DiagnosticIssue]
    probes: list[ProbeResult]


def analyze_snapshot_file(
    snapshot_path: Path,
    output_directory: Path,
    *,
    provider: str = "anthropic",
    model: str | None = None,
    effort: str = _DEFAULT_EFFORT,
    investigate: bool = False,
    focus: str | None = None,
    scan_id: str | None = None,
    collection_duration_seconds: float | None = None,
    progress: ProgressCallback | None = None,
) -> AnalysisOutcome:
    """Analyze a saved snapshot and write compact plus detailed agentic reports."""

    if progress:
        progress(1, "Preparing and redacting system evidence…")
    snapshot = _load_snapshot(snapshot_path)
    resolved_scan_id = scan_id or output_directory.name
    snapshot_sha256 = hashlib.sha256(snapshot_path.read_bytes()).hexdigest()
    paths = AgentReportPaths(
        compact=output_directory / "compact_snapshot.html",
        blueprint=output_directory / "system-blueprint.html",
        diagnostics=output_directory / "diagnostic-report.html",
        analysis=output_directory / "agent-analysis.json",
    )
    deterministic_baseline = _deterministic_issues(snapshot)
    accepted_issues = deterministic_baseline
    summary = _deterministic_summary(snapshot)
    observations = _architecture_observations(snapshot)
    unknowns = _unknowns(snapshot)
    probes: list[ProbeResult] = []
    provider_status = "deterministic analysis"
    provider_response: ProviderResponse | None = None

    if provider not in PROVIDER_CHOICES:
        raise ValueError("provider must be one of: " + ", ".join(PROVIDER_CHOICES))
    if effort not in EFFORT_CHOICES:
        raise ValueError("effort must be one of: " + ", ".join(EFFORT_CHOICES))

    resolved_model = resolve_model(provider, model) if provider != "none" else "none"
    if provider != "none":
        adapter = get_provider(provider)
        try:
            if progress:
                progress(2, f"Sending evidence to {adapter.display_name}…")
                progress(3, f"Waiting for {resolved_model} analysis…", True)
            provider_response = _provider_analysis(
                snapshot,
                deterministic_baseline,
                provider=adapter,
                model=resolved_model,
                effort=effort,
                focus=focus,
            )
        except AgentProviderError as exception:
            provider_status = (
                f"{adapter.display_name} unavailable; deterministic fallback ({exception})"
            )
        else:
            if progress:
                progress(4, "Validating findings against collected evidence…")
            provider_status = _provider_status(adapter, resolved_model, provider_response)
            response = provider_response.analysis
            summary = _clean_text(response.get("summary")) or summary
            observations = _string_list(response.get("architecture_observations")) or observations
            unknowns = _string_list(response.get("unknowns")) or unknowns
            accepted_issues = _merge_agent_issues(
                snapshot,
                deterministic_baseline,
                response.get("issues"),
            )
            requests = _parse_probe_requests(response.get("probe_requests"))

            if investigate and requests:
                probes = _run_probe_requests(snapshot, requests)
                if probes:
                    try:
                        revised_response = _provider_analysis(
                            snapshot,
                            deterministic_baseline,
                            provider=adapter,
                            model=resolved_model,
                            effort=effort,
                            focus=focus,
                            probe_results=probes,
                        )
                    except AgentProviderError:
                        provider_status += "; probe re-analysis unavailable"
                    else:
                        provider_status += f"; {len(probes)} read-only probes evaluated"
                        provider_response = revised_response
                        revised = revised_response.analysis
                        summary = _clean_text(revised.get("summary")) or summary
                        observations = (
                            _string_list(revised.get("architecture_observations")) or observations
                        )
                        unknowns = _string_list(revised.get("unknowns")) or unknowns
                        # A second pass replaces the first pass's hypotheses. It may
                        # retract an issue disproved by the read-only probe results.
                        accepted_issues = _merge_agent_issues(
                            snapshot,
                            deterministic_baseline,
                            revised.get("issues"),
                        )

    if progress and provider == "none":
        progress(4, "Validating deterministic findings against collected evidence…")
    if progress:
        progress(5, "Generating diagnostic reports…")
    output_directory.mkdir(parents=True, exist_ok=True)
    context = build_report_context(
        snapshot,
        issues=[issue.to_dict() for issue in accepted_issues],
        summary=summary,
        observations=observations,
        unknowns=unknowns,
        provider_status=provider_status,
        scan_id=resolved_scan_id,
        snapshot_sha256=snapshot_sha256,
        collection_duration_seconds=collection_duration_seconds,
        focus=focus,
    )
    if progress:
        progress(6, "Saving reports and manifests…")
    paths.compact.write_text(render_compact_snapshot(context), encoding="utf-8")
    paths.blueprint.write_text(
        render_system_blueprint(context, snapshot),
        encoding="utf-8",
    )
    paths.diagnostics.write_text(
        render_diagnostic_report(context, [probe.to_dict() for probe in probes]),
        encoding="utf-8",
    )
    paths.analysis.write_text(
        json.dumps(
            {
                "source_snapshot": str(snapshot_path),
                "scan_id": resolved_scan_id,
                "snapshot_sha256": snapshot_sha256,
                "screwdriver_version": __version__,
                "provider": provider,
                "model": resolved_model,
                "requested_effort": effort,
                "provider_status": provider_status,
                "provider_request": _provider_metadata(provider_response),
                "focus": focus,
                "summary": summary,
                "overall_evidence_state": context["overall"],
                "highest_priority_next_check": context["priority"],
                "successful_checks": context["checks"],
                "collection_coverage": context["coverage"],
                "architecture_observations": observations,
                "unknowns": unknowns,
                "issues": [issue.to_dict() for issue in accepted_issues],
                "read_only_probes": [probe.to_dict() for probe in probes],
                "repairs_executed": False,
            },
            indent=2,
        )
        + "\n",
        encoding="utf-8",
    )
    (output_directory / "report-manifest.json").write_text(
        json.dumps(
            {
                "report_kind": "agentic",
                "scan_id": resolved_scan_id,
                "source_snapshot": str(snapshot_path),
                "snapshot_sha256": snapshot_sha256,
                "screwdriver_version": __version__,
                "provider": provider,
                "model": resolved_model,
                "requested_effort": effort,
                "provider_status": provider_status,
                "provider_request": _provider_metadata(provider_response),
                "fallback_used": "fallback" in provider_status.lower(),
                "artifacts": [
                    paths.compact.name,
                    paths.blueprint.name,
                    paths.diagnostics.name,
                    paths.analysis.name,
                ],
                "repairs_executed": False,
            },
            indent=2,
        )
        + "\n",
        encoding="utf-8",
    )
    update_latest_reference(output_directory)
    return AnalysisOutcome(
        paths=paths,
        provider_status=provider_status,
        summary=summary,
        architecture_observations=observations,
        unknowns=unknowns,
        issues=accepted_issues,
        probes=probes,
    )


def _provider_metadata(response: ProviderResponse | None) -> dict[str, object]:
    if response is None:
        return {}
    return {
        "request_id": response.request_id,
        "input_tokens": response.input_tokens,
        "output_tokens": response.output_tokens,
        "duration_ms": response.request_duration_ms,
        "api_effort": response.api_effort,
        "used_model_default_effort": response.used_model_default_effort,
    }


def _load_snapshot(path: Path) -> dict[str, Any]:
    try:
        raw = json.loads(path.read_text(encoding="utf-8"))
    except OSError as exception:
        raise ValueError(f"cannot read snapshot: {exception}") from exception
    except json.JSONDecodeError as exception:
        raise ValueError(f"snapshot is not valid JSON: {exception}") from exception

    if not isinstance(raw, dict):
        raise ValueError("snapshot root must be a JSON object")
    required = {"identity", "operating_system", "cpu", "memory", "network", "findings"}
    missing = sorted(required - raw.keys())
    if missing:
        raise ValueError("snapshot is missing required fields: " + ", ".join(missing))
    return cast(dict[str, Any], raw)


def _deterministic_summary(snapshot: dict[str, Any]) -> str:
    identity = _mapping(snapshot.get("identity"))
    os_info = _mapping(snapshot.get("operating_system"))
    platform = _mapping(snapshot.get("platform"))
    ros = _ros_overview(snapshot)
    devices = _current_ros_device_names(snapshot)
    machine = platform.get("product_name") or platform.get("board_name") or "Linux computer"
    graph = ""
    if ros:
        graph = (
            f" The live ROS 2 graph contains {ros.get('nodes', 0)} nodes and "
            f"{ros.get('topics', 0)} topics."
        )
    device_text = f" ROS currently uses {', '.join(devices)}." if devices else ""
    return (
        f"{identity.get('hostname', 'This robotic computer')} is a {machine} running "
        f"{os_info.get('distribution', 'Linux')}.{graph}{device_text}"
    )


def _architecture_observations(snapshot: dict[str, Any]) -> list[str]:
    observations: list[str] = []
    ros = _ros_overview(snapshot)
    if ros:
        observations.append(
            "ROS 2 uses "
            f"{ros.get('middleware') or 'an unspecified DDS implementation'} on domain "
            f"{ros.get('domain_id') if ros.get('domain_id') is not None else 'unknown'}."
        )
    for device in _records(snapshot.get("ros_device_inventory"))[:12]:
        details = _mapping(device.get("details"))
        kind = details.get("kind") or device.get("name")
        node = details.get("ros_node") or details.get("hardware_node")
        channel = details.get("topics") or details.get("channel")
        physical = details.get("physical_component")
        chain = " → ".join(str(value) for value in (physical, node, channel) if value)
        if chain:
            observations.append(f"{kind}: {chain}")
    return observations


def _unknowns(snapshot: dict[str, Any]) -> list[str]:
    unknowns: list[str] = []
    for device in _records(snapshot.get("ros_device_inventory")):
        details = _mapping(device.get("details"))
        if not details.get("physical_component"):
            unknowns.append(
                f"{details.get('kind') or device.get('name')}: physical hardware is not proven."
            )
    for device in _records(snapshot.get("serial_devices")):
        if not device.get("stable_id_path"):
            unknowns.append(
                f"{device.get('port', 'Serial device')}: no stable by-id identity was found."
            )
    return _deduplicate_text(unknowns)


def _deterministic_issues(snapshot: dict[str, Any]) -> list[DiagnosticIssue]:
    issues: list[DiagnosticIssue] = []
    ros_runtime = _ros_overview(snapshot)
    for finding_index, finding in enumerate(_records(snapshot.get("findings"))):
        severity = str(finding.get("severity") or "info").lower()
        code = str(finding.get("code") or "UNCLASSIFIED_FINDING")
        if severity == "info" and code.endswith(("_HEALTHY", "_DETECTED", "_DISCOVERED")):
            continue
        summary = _clean_text(finding.get("summary")) or code.replace("_", " ").title()
        evidence = _clean_text(finding.get("evidence"))
        recommendation = _clean_text(finding.get("recommendation"))
        steps = _recommendation_steps(recommendation, code)
        classification = _classification_for_finding(code, severity, snapshot)
        rendered_severity = _severity_label(severity)
        if classification in {"ADVISORY", "NEEDS_CONFIRMATION"}:
            rendered_severity = "INFO"
        if (
            code == "ROS_ENVIRONMENT_NOT_SOURCED"
            and str(ros_runtime.get("state") or "").upper() == "RUNNING"
            and ros_runtime.get("environment_recovered")
        ):
            classification = "ADVISORY"
            rendered_severity = "INFO"
        issues.append(
            DiagnosticIssue(
                code=code,
                title=summary.removeprefix("[OK] "),
                severity=rendered_severity,
                confidence=95 if evidence else 70,
                classification=classification,
                observation_confidence=100 if evidence else 75,
                diagnosis_confidence=70 if evidence else 45,
                expected_state=_expected_state_for_code(code),
                operational_impact=_impact_for_code(code, classification),
                evidence_references=[f"findings[{finding_index}]"],
                observed=[evidence] if evidence else [summary],
                probable_causes=[_default_cause(code)],
                primary_approach=steps,
                diagnostic_commands=_commands_for_code(code, finding),
                success_criteria=[_success_for_code(code)],
                evidence_level="VERIFIED" if evidence else "CORRELATED",
            )
        )

    runtime = _ros_overview(snapshot)
    if runtime and str(runtime.get("state") or "").upper() in {"UNAVAILABLE", "FAILED"}:
        if not any(issue.code == "ROS_RUNTIME_UNAVAILABLE" for issue in issues):
            issues.append(
                DiagnosticIssue(
                    code="ROS_RUNTIME_UNAVAILABLE",
                    title="ROS 2 runtime graph could not be inspected",
                    severity="HIGH",
                    confidence=95,
                    classification="DEGRADED",
                    observation_confidence=95,
                    diagnosis_confidence=65,
                    expected_state="The expected ROS 2 graph is discoverable from the inspection environment.",
                    operational_impact="Screwdriver cannot verify active ROS nodes, endpoints, or ROS-linked hardware.",
                    evidence_references=["ros_runtime_inventory"],
                    observed=[f"ROS graph state: {runtime.get('state')}"],
                    probable_causes=[
                        "The scanner and ROS processes may use different environment or DDS settings."
                    ],
                    primary_approach=[
                        "Source the same ROS underlay and workspace used to launch the robot.",
                        "Verify ROS_DOMAIN_ID and RMW_IMPLEMENTATION.",
                        "Run ros2 node list and confirm that the graph is visible.",
                        "Repeat the Screwdriver inspection.",
                    ],
                    diagnostic_commands=["ros2 node list", "ros2 topic list -t"],
                    success_criteria=[
                        "The ROS graph is discovered and reports active nodes/topics."
                    ],
                )
            )
    return _deduplicate_issues(issues)


def _classification_for_finding(
    code: str,
    severity: str,
    snapshot: dict[str, Any],
) -> str:
    if code.startswith("SERIAL_") and not _serial_finding_is_operationally_relevant(code, snapshot):
        return "NEEDS_CONFIRMATION"
    if severity == "error":
        return "CONFIRMED_FAILURE"
    if code.startswith(("CPU_", "MEMORY_", "FILESYSTEM_", "THERMAL_")):
        return "DEGRADED"
    if code.startswith(("ROS_", "DDS_", "SERIAL_")):
        return "CONFIGURATION_WARNING"
    if severity == "warning":
        return "NEEDS_CONFIRMATION"
    return "ADVISORY"


def _serial_finding_is_operationally_relevant(code: str, snapshot: dict[str, Any]) -> bool:
    if not code.startswith("SERIAL_"):
        return False
    ros_text = json.dumps(snapshot.get("ros_device_inventory", []), ensure_ascii=False)
    for device in _records(snapshot.get("serial_devices")):
        for identity in (device.get("port"), device.get("stable_id_path")):
            if identity and str(identity) in ros_text:
                return True
    return False


def _expected_state_for_code(code: str) -> str:
    if code.startswith("ROS_"):
        return "The configured ROS environment and expected runtime graph are mutually consistent."
    if code.startswith("SERIAL_"):
        return "Only serial interfaces required by the robot profile or runtime need stable, read-write access."
    if code.startswith("CPU_"):
        return "CPU usage remains below the warning threshold during the expected workload."
    if code.startswith("MEMORY_"):
        return "Memory use remains below the warning threshold without sustained growth."
    if code.startswith("FILESYSTEM_"):
        return "Runtime filesystems retain enough capacity for logs and application data."
    if code.startswith("THERMAL_"):
        return "Temperature remains below the sensor or platform critical limit."
    return "The component matches the robot's declared expected state."


def _impact_for_code(code: str, classification: str) -> str:
    if classification == "NEEDS_CONFIRMATION":
        return "No operational impact is proven until the operator confirms this component is required."
    if code.startswith("ROS_"):
        return "ROS discovery, startup consistency, or communication visibility may be affected."
    if code.startswith("SERIAL_"):
        return "A process that requires this serial interface may be unable to open it reliably."
    if code.startswith("CPU_"):
        return "Control, perception, or interaction workloads may miss timing targets."
    if code.startswith("MEMORY_"):
        return "Processes may experience reclaim pressure, latency, or termination if usage grows."
    if code.startswith("FILESYSTEM_"):
        return "Logs, recordings, datasets, or application writes may fail when capacity is exhausted."
    if code.startswith("THERMAL_"):
        return "The computer may throttle or shut down to protect hardware."
    return "The affected robot capability and operating impact require confirmation."


def _provider_analysis(
    snapshot: dict[str, Any],
    issues: list[DiagnosticIssue],
    *,
    provider: AgentProvider,
    model: str,
    effort: str,
    focus: str | None,
    probe_results: list[ProbeResult] | None = None,
) -> ProviderResponse:
    schema = _agent_schema()
    evidence = {
        "snapshot": _evidence_view(snapshot),
        "deterministic_issues": [issue.to_dict() for issue in issues],
        "focus": focus,
        "read_only_probe_results": [probe.to_dict() for probe in probe_results or []],
    }
    system = (
        "You are Screwdriver's robotics diagnostic engineer. Use only supplied evidence. "
        "Never claim hardware was tested, never invent facts, and distinguish verified, "
        "correlated, inferred, and unknown information. Do not turn an absent, down, unused, "
        "or unreferenced component into a fault unless an expected state proves it is required. "
        "A ROS publisher/subscriber relationship proves graph participation, not ownership of "
        "physical hardware. Deterministic issues are baseline evidence, but you may classify "
        "conditional observations as advisories or operator-confirmation items. "
        "For each problem, provide ordered troubleshooting approaches and measurable success "
        "criteria and exact snapshot evidence references. Separate confidence in the observation "
        "from confidence in the diagnosis. You may request only the listed read-only probes. "
        "Never recommend that the "
        "software execute repairs, actuator commands, permission changes, installs, restarts, "
        "or configuration edits automatically. Return JSON matching the supplied schema."
    )
    if probe_results:
        system += " Probe results are final evidence; do not request additional probes."
    user = (
        "Build (1) a concise system-blueprint narrative and (2) an evidence-grounded "
        "diagnostic plan. Allowed probes: ros_node_info, ros_topic_info, ros_param_list, "
        "device_metadata, port_owner, service_status, recent_kernel_logs, network_link.\n\n"
        + json.dumps(evidence, separators=(",", ":"))
    )
    return provider.analyze(
        ProviderRequest(
            model=model,
            effort=effort,
            max_output_tokens=_MAX_OUTPUT_TOKENS,
            system=system,
            user=user,
            schema=schema,
        )
    )


def _provider_status(
    provider: AgentProvider,
    model: str,
    response: ProviderResponse,
) -> str:
    """Describe both the chosen model and its actual effort behavior."""

    if response.used_model_default_effort:
        effort = f"model default; requested {response.requested_effort} unsupported"
    else:
        effort = response.requested_effort
    return f"{provider.display_name} model {model} (effort {effort})"


