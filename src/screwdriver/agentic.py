def _architecture_rows(devices: list[dict[str, Any]]) -> list[list[Any]]:
    rows: list[list[Any]] = []
    for device in devices:
        details = _mapping(device.get("details"))
        rows.append(
            [
                details.get("physical_component") or "Unresolved",
                details.get("physical_channel")
                or details.get("physical_bus")
                or details.get("bus"),
                details.get("ros_node") or details.get("hardware_node"),
                details.get("topics") or details.get("channel") or details.get("ros_endpoint"),
                details.get("kind") or device.get("name"),
                details.get("confidence") or "UNKNOWN",
            ]
        )
    return rows


def _flow_rows(devices: list[dict[str, Any]]) -> list[list[Any]]:
    rows: list[list[Any]] = []
    for device in devices:
        details = _mapping(device.get("details"))
        rows.append(
            [
                details.get("physical_component") or details.get("kind") or device.get("name"),
                details.get("ros_node") or details.get("hardware_node"),
                details.get("topics") or details.get("channel") or details.get("ros_endpoint"),
                details.get("direction"),
                details.get("kind"),
            ]
        )
    return rows


def _current_ros_device_names(snapshot: dict[str, Any]) -> list[str]:
    aliases = {
        "camera": "Camera",
        "lidar": "LiDAR",
        "point-cloud sensor": "Point-cloud sensor",
        "imu": "IMU",
        "gps/gnss": "GPS/GNSS",
        "microphone": "Microphone",
        "microphone / audio capture": "Microphone",
        "speaker / audio output": "Speaker",
        "display / visual output": "Display unit",
        "mobile base drive": "Mobile base",
        "motor / actuator controller": "Motor / actuator",
        "gripper": "Gripper",
        "power / battery device": "Battery / power system",
    }
    names: list[str] = []
    for device in _records(snapshot.get("ros_device_inventory")):
        details = _mapping(device.get("details"))
        if str(details.get("state") or "").upper() not in {"IN_USE_BY_ROS", "ACTIVE", "RUNNING"}:
            continue
        kind = str(details.get("kind") or device.get("name") or "Other ROS device")
        names.append(aliases.get(kind.lower(), kind.replace("_", " ").capitalize()))
    return _deduplicate_text(names)


def _ros_overview(snapshot: dict[str, Any]) -> dict[str, Any]:
    for item in _records(snapshot.get("ros_runtime_inventory")):
        if item.get("category") == "ROS runtime":
            return _mapping(item.get("details"))
    return {}


